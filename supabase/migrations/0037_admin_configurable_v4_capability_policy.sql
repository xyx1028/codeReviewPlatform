-- Make V4 operational capability limits ADMIN-configurable per model.
--
-- Security model:
--   * v4_harness_manifest remains the immutable capability/safety baseline;
--   * only resource limits already represented by ai_model_config are writable;
--   * build_v4_capability_policy(uuid) remains the only runtime policy builder;
--   * analysis_job snapshots stay immutable, so updates affect new Jobs only.

begin;

create table if not exists public.v4_capability_policy_audit (
  id bigint generated by default as identity primary key,
  model_config_id uuid references public.ai_model_config(id) on delete set null,
  model_display_name_snapshot text not null,
  old_policy jsonb not null check (jsonb_typeof(old_policy) = 'object'),
  new_policy jsonb not null check (jsonb_typeof(new_policy) = 'object'),
  changed_by uuid references public.user_profile(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists idx_v4_capability_policy_audit_model_created
  on public.v4_capability_policy_audit(model_config_id, created_at desc);

alter table public.v4_capability_policy_audit enable row level security;
revoke all on table public.v4_capability_policy_audit from public, anon, authenticated;
grant select on table public.v4_capability_policy_audit to authenticated, service_role;

drop policy if exists "admins read V4 capability policy audit"
  on public.v4_capability_policy_audit;
create policy "admins read V4 capability policy audit"
  on public.v4_capability_policy_audit
  for select
  to authenticated
  using (public.is_admin());

-- The parameterized overload returns the exact policy that a new Job using the
-- selected model would freeze. Keep the no-argument overload from 0036 during
-- rolling deployment so the previous frontend remains readable.
create or replace function public.admin_get_v4_capability_policy(
  p_model_config_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
stable
as $$
declare
  v_policy jsonb;
begin
  perform public.ensure_admin();

  select public.build_v4_capability_policy(p_model_config_id) into v_policy;
  if v_policy is null then
    raise exception 'V4_MODEL_CONFIG_NOT_FOUND';
  end if;

  return v_policy;
end;
$$;

-- Explicit scalar parameters are intentional: callers cannot smuggle capability
-- switches or safety invariants (dangerFullAccess, HTTP, private networks, etc.)
-- into the update payload.
create or replace function public.admin_update_v4_capability_policy(
  p_model_config_id uuid,
  p_sandbox_command_timeout_ms integer,
  p_sandbox_max_processes integer,
  p_workspace_max_bytes bigint,
  p_workspace_max_files integer,
  p_max_agents_per_attempt integer,
  p_max_delegation_depth integer,
  p_max_concurrent_children integer,
  p_workflow_max_concurrent_steps integer,
  p_workflow_max_runtime_ms integer,
  p_max_concurrent_jobs_per_owner integer,
  p_jobs_max_runtime_ms integer,
  p_max_parallel_tool_calls integer,
  p_agent_max_total_requests integer,
  p_agent_max_root_requests integer,
  p_agent_max_child_requests integer,
  p_agent_max_retry_requests integer,
  p_agent_max_compaction_requests integer,
  p_agent_max_ralph_rounds integer,
  p_web_max_requests_per_attempt integer,
  p_web_max_response_bytes bigint,
  p_web_max_total_bytes bigint,
  p_web_allowed_domains text[],
  p_session_checkpoint_every_events integer,
  p_session_retention_days integer
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_model public.ai_model_config%rowtype;
  v_domains text[];
  v_old_policy jsonb;
  v_new_policy jsonb;
begin
  perform public.ensure_admin();

  select * into v_model
  from public.ai_model_config
  where id = p_model_config_id
  for update;

  if not found then
    raise exception 'V4_MODEL_CONFIG_NOT_FOUND';
  end if;

  if p_sandbox_command_timeout_ms is null
     or p_sandbox_max_processes is null
     or p_workspace_max_bytes is null
     or p_workspace_max_files is null
     or p_max_agents_per_attempt is null
     or p_max_delegation_depth is null
     or p_max_concurrent_children is null
     or p_workflow_max_concurrent_steps is null
     or p_workflow_max_runtime_ms is null
     or p_max_concurrent_jobs_per_owner is null
     or p_jobs_max_runtime_ms is null
     or p_max_parallel_tool_calls is null
     or p_agent_max_total_requests is null
     or p_agent_max_root_requests is null
     or p_agent_max_child_requests is null
     or p_agent_max_retry_requests is null
     or p_agent_max_compaction_requests is null
     or p_agent_max_ralph_rounds is null
     or p_web_max_requests_per_attempt is null
     or p_web_max_response_bytes is null
     or p_web_max_total_bytes is null
     or p_session_checkpoint_every_events is null
     or p_session_retention_days is null then
    raise exception 'V4_POLICY_REQUIRED_FIELD_MISSING';
  end if;

  if p_agent_max_root_requests > p_agent_max_total_requests
     or p_agent_max_child_requests > p_agent_max_total_requests
     or p_agent_max_retry_requests > p_agent_max_total_requests
     or p_agent_max_compaction_requests > p_agent_max_total_requests then
    raise exception 'V4_POLICY_BUDGET_INCONSISTENT';
  end if;

  if exists (
    select 1
    from unnest(coalesce(p_web_allowed_domains, array[]::text[])) as item(domain)
    where btrim(domain) <> ''
      and (
        lower(btrim(domain)) !~ '^[a-z0-9.-]+$'
        or position('/' in domain) > 0
        or position(' ' in domain) > 0
      )
  ) then
    raise exception 'V4_POLICY_DOMAIN_INVALID';
  end if;

  select coalesce(array_agg(normalized.domain order by normalized.domain), array[]::text[])
  into v_domains
  from (
    select distinct lower(btrim(item.domain)) as domain
    from unnest(coalesce(p_web_allowed_domains, array[]::text[])) as item(domain)
    where btrim(item.domain) <> ''
  ) normalized;

  v_old_policy := public.build_v4_capability_policy(p_model_config_id);

  update public.ai_model_config
  set
    sandbox_command_timeout_ms = p_sandbox_command_timeout_ms,
    sandbox_max_processes = p_sandbox_max_processes,
    workspace_max_bytes = p_workspace_max_bytes,
    workspace_max_files = p_workspace_max_files,
    max_agents_per_attempt = p_max_agents_per_attempt,
    max_delegation_depth = p_max_delegation_depth,
    max_concurrent_children = p_max_concurrent_children,
    workflow_max_concurrent_steps = p_workflow_max_concurrent_steps,
    workflow_max_runtime_ms = p_workflow_max_runtime_ms,
    max_concurrent_jobs_per_owner = p_max_concurrent_jobs_per_owner,
    jobs_max_runtime_ms = p_jobs_max_runtime_ms,
    max_parallel_tool_calls = p_max_parallel_tool_calls,
    agent_max_total_requests = p_agent_max_total_requests,
    agent_max_root_requests = p_agent_max_root_requests,
    agent_max_child_requests = p_agent_max_child_requests,
    agent_max_retry_requests = p_agent_max_retry_requests,
    agent_max_compaction_requests = p_agent_max_compaction_requests,
    agent_max_ralph_rounds = p_agent_max_ralph_rounds,
    web_max_requests_per_attempt = p_web_max_requests_per_attempt,
    web_max_response_bytes = p_web_max_response_bytes,
    web_max_total_bytes = p_web_max_total_bytes,
    web_allowed_domains = v_domains,
    session_checkpoint_every_events = p_session_checkpoint_every_events,
    session_retention_days = p_session_retention_days,
    updated_at = now()
  where id = p_model_config_id;

  v_new_policy := public.build_v4_capability_policy(p_model_config_id);

  if v_new_policy is distinct from v_old_policy then
    insert into public.v4_capability_policy_audit (
      model_config_id,
      model_display_name_snapshot,
      old_policy,
      new_policy,
      changed_by
    ) values (
      p_model_config_id,
      v_model.display_name,
      v_old_policy,
      v_new_policy,
      auth.uid()
    );
  end if;

  return v_new_policy;
end;
$$;

revoke execute on function public.admin_get_v4_capability_policy(uuid)
  from public, anon;
grant execute on function public.admin_get_v4_capability_policy(uuid)
  to authenticated, service_role;

revoke execute on function public.admin_update_v4_capability_policy(
  uuid, integer, integer, bigint, integer, integer, integer, integer,
  integer, integer, integer, integer, integer, integer, integer, integer,
  integer, integer, integer, integer, bigint, bigint, text[], integer, integer
) from public, anon;
grant execute on function public.admin_update_v4_capability_policy(
  uuid, integer, integer, bigint, integer, integer, integer, integer,
  integer, integer, integer, integer, integer, integer, integer, integer,
  integer, integer, integer, integer, bigint, bigint, text[], integer, integer
) to authenticated, service_role;

comment on function public.admin_get_v4_capability_policy(uuid) is
  'ADMIN only: returns the exact V4 policy a new Job for the selected model would freeze.';
comment on function public.admin_update_v4_capability_policy(
  uuid, integer, integer, bigint, integer, integer, integer, integer,
  integer, integer, integer, integer, integer, integer, integer, integer,
  integer, integer, integer, integer, bigint, bigint, text[], integer, integer
) is
  'ADMIN only: updates per-model V4 operational limits; immutable capability and safety fields are not accepted.';
