-- V1.8：技能目录容量上限平台级可配置。
--
-- 把技能目录的四项容量上限（catalogBundles / catalogRenderBytes / catalogArchiveBytes /
-- catalogExpandedBytes）从写死的常量改为管理员可配置的平台级单例。
--
-- 关键不变式（见 V1.8 执行方案 §0、§3-D3）：
--   * 单包上限（archiveBytes / expandedBytes / entryCount / fileBytes / entryFileBytes /
--     pathDepth / pathBytes / compressionRatio / validateMs）仍是写死的安全边界，本期不放开。
--   * 目录四项改为从 skill_catalog_limits_config 读取。
--   * 出厂默认 = 升级前的现值，纯 expand-only，行为零变化。
--   * Job 冻结时把「当时生效的目录四项」冻进 analysis_job.skill_catalog_limits，
--     get_story_task_skill_snapshot 原样返回；Worker 用这份冻结值重算校验，
--     从而与数据库冻结校验用同一组数字——杜绝「界面改了、Worker 用旧常量、批次起不来」。
--   * limits 不参与 catalog identity（skill_catalog_hash），所以不动 hash 逻辑。

begin;

------------------------------------------------------------------------------
-- 1. 平台级单例配置表 + 审计表
------------------------------------------------------------------------------

create table if not exists public.skill_catalog_limits_config (
  id smallint primary key default 1 check (id = 1),
  catalog_bundles integer not null default 50
    check (catalog_bundles between 1 and 200),
  catalog_render_bytes bigint not null default 32 * 1024
    check (catalog_render_bytes between 8 * 1024 and 128 * 1024),
  catalog_archive_bytes bigint not null default 100 * 1024 * 1024
    check (catalog_archive_bytes between 10 * 1024 * 1024 and 1024 * 1024 * 1024),
  catalog_expanded_bytes bigint not null default 256 * 1024 * 1024
    check (catalog_expanded_bytes between 50 * 1024 * 1024 and 2::bigint * 1024 * 1024 * 1024),
  updated_by uuid references public.user_profile(id) on delete set null,
  updated_at timestamptz not null default now()
);

comment on table public.skill_catalog_limits_config is
  '平台级技能目录容量上限（单例，id=1）。目录四项从这里读；单包上限仍是 skill_bundle_limits() 里的常量。';

-- 出厂单例行：值等于升级前的常量，所以升级后行为零变化。
insert into public.skill_catalog_limits_config (id)
values (1)
on conflict (id) do nothing;

alter table public.skill_catalog_limits_config enable row level security;
revoke all on table public.skill_catalog_limits_config from public, anon;
-- authenticated 只读（技能页/能力策略页要展示当前值）；写入只走 security definer RPC。
grant select on table public.skill_catalog_limits_config to authenticated, service_role;

drop policy if exists "authenticated read skill catalog limits"
  on public.skill_catalog_limits_config;
create policy "authenticated read skill catalog limits"
  on public.skill_catalog_limits_config
  for select
  to authenticated
  using (true);

create table if not exists public.skill_catalog_limits_audit (
  id bigint generated by default as identity primary key,
  old_limits jsonb not null check (jsonb_typeof(old_limits) = 'object'),
  new_limits jsonb not null check (jsonb_typeof(new_limits) = 'object'),
  changed_by uuid references public.user_profile(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists idx_skill_catalog_limits_audit_created
  on public.skill_catalog_limits_audit(created_at desc);

alter table public.skill_catalog_limits_audit enable row level security;
revoke all on table public.skill_catalog_limits_audit from public, anon, authenticated;
grant select on table public.skill_catalog_limits_audit to authenticated, service_role;

drop policy if exists "admins read skill catalog limits audit"
  on public.skill_catalog_limits_audit;
create policy "admins read skill catalog limits audit"
  on public.skill_catalog_limits_audit
  for select
  to authenticated
  using (public.is_admin());

------------------------------------------------------------------------------
-- 2. 读写 RPC
------------------------------------------------------------------------------

create or replace function public.admin_get_skill_catalog_limits()
returns jsonb
language plpgsql
security definer
set search_path = public
stable
as $$
declare
  v_row public.skill_catalog_limits_config;
begin
  perform public.ensure_admin();
  select * into v_row from public.skill_catalog_limits_config where id = 1;
  if not found then
    raise exception 'SKILL_CATALOG_LIMITS_NOT_INITIALIZED';
  end if;
  return jsonb_build_object(
    'catalogBundles', v_row.catalog_bundles,
    'catalogRenderBytes', v_row.catalog_render_bytes,
    'catalogArchiveBytes', v_row.catalog_archive_bytes,
    'catalogExpandedBytes', v_row.catalog_expanded_bytes,
    'updatedAt', v_row.updated_at
  );
end;
$$;

revoke execute on function public.admin_get_skill_catalog_limits() from public, anon;
grant execute on function public.admin_get_skill_catalog_limits() to authenticated;

-- 区间校验刻意在这里再做一次（表 check 之外）：给出稳定错误码，而不是让前端拿到一个
-- 通用的 check 违反消息。任一项 null 直接拒——update 是全量覆盖，不允许半配置。
create or replace function public.admin_update_skill_catalog_limits(
  p_catalog_bundles integer,
  p_catalog_render_bytes bigint,
  p_catalog_archive_bytes bigint,
  p_catalog_expanded_bytes bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old jsonb;
  v_new jsonb;
begin
  perform public.ensure_admin();

  if p_catalog_bundles is null
     or p_catalog_render_bytes is null
     or p_catalog_archive_bytes is null
     or p_catalog_expanded_bytes is null then
    raise exception 'SKILL_CATALOG_LIMITS_INCOMPLETE';
  end if;

  if p_catalog_bundles < 1 or p_catalog_bundles > 200 then
    raise exception 'SKILL_CATALOG_LIMITS_OUT_OF_RANGE';
  end if;
  if p_catalog_render_bytes < 8 * 1024 or p_catalog_render_bytes > 128 * 1024 then
    raise exception 'SKILL_CATALOG_LIMITS_OUT_OF_RANGE';
  end if;
  if p_catalog_archive_bytes < 10 * 1024 * 1024
     or p_catalog_archive_bytes > 1024 * 1024 * 1024 then
    raise exception 'SKILL_CATALOG_LIMITS_OUT_OF_RANGE';
  end if;
  if p_catalog_expanded_bytes < 50 * 1024 * 1024
     or p_catalog_expanded_bytes > 2::bigint * 1024 * 1024 * 1024 then
    raise exception 'SKILL_CATALOG_LIMITS_OUT_OF_RANGE';
  end if;

  v_old := public.admin_get_skill_catalog_limits();

  update public.skill_catalog_limits_config
  set catalog_bundles = p_catalog_bundles,
      catalog_render_bytes = p_catalog_render_bytes,
      catalog_archive_bytes = p_catalog_archive_bytes,
      catalog_expanded_bytes = p_catalog_expanded_bytes,
      updated_by = auth.uid(),
      updated_at = now()
  where id = 1;

  v_new := public.admin_get_skill_catalog_limits();

  insert into public.skill_catalog_limits_audit (old_limits, new_limits, changed_by)
  values (v_old, v_new, auth.uid());

  return v_new;
end;
$$;

revoke execute on function public.admin_update_skill_catalog_limits(integer, bigint, bigint, bigint)
  from public, anon;
grant execute on function public.admin_update_skill_catalog_limits(integer, bigint, bigint, bigint)
  to authenticated;

------------------------------------------------------------------------------
-- 3. skill_bundle_limits()：目录四项改为读配置表，单包项仍为常量
--
-- 从 immutable 降为 stable：现在读表了，不能再声明 immutable。
------------------------------------------------------------------------------

create or replace function public.skill_bundle_limits()
returns jsonb
language sql
stable
as $$
  select jsonb_build_object(
    'archiveBytes', 10 * 1024 * 1024,
    'expandedBytes', 50 * 1024 * 1024,
    'entryCount', 200,
    'fileBytes', 10 * 1024 * 1024,
    'entryFileBytes', 64 * 1024,
    'pathDepth', 8,
    'pathBytes', 240,
    'compressionRatio', 20,
    'validateMs', 30000,
    'catalogBundles', (select catalog_bundles from public.skill_catalog_limits_config where id = 1),
    'descriptionChars', 500,
    'catalogRenderBytes', (select catalog_render_bytes from public.skill_catalog_limits_config where id = 1),
    'catalogArchiveBytes', (select catalog_archive_bytes from public.skill_catalog_limits_config where id = 1),
    'catalogExpandedBytes', (select catalog_expanded_bytes from public.skill_catalog_limits_config where id = 1)
  );
$$;

------------------------------------------------------------------------------
-- 4. Job 冻结时把目录四项冻进 analysis_job；快照 RPC 原样返回
--
-- limits 不参与 catalog identity（skill_catalog_hash 不变），只是让 Worker 能拿到
-- 「冻结那一刻的目录上限」用于启动重算，与数据库冻结校验对齐。
------------------------------------------------------------------------------

alter table public.analysis_job
  add column if not exists skill_catalog_limits jsonb;

comment on column public.analysis_job.skill_catalog_limits is
  'Job 冻结时生效的技能目录四项上限快照。Worker 用它重算校验；null = 历史 Job，Worker 回退编译默认。';

-- 重建 freeze 函数：在算完容量后，把本次用的目录四项写进 analysis_job.skill_catalog_limits。
create or replace function public.freeze_analysis_job_skill_catalog(p_job_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_limits jsonb := public.skill_bundle_limits();
  v_entries jsonb := public.current_skill_catalog_entries();
  v_entry jsonb;
  v_count integer := jsonb_array_length(v_entries);
  v_archive_bytes bigint := 0;
  v_expanded_bytes bigint := 0;
  v_render_bytes bigint := 0;
  v_hash text;
begin
  if v_count > (v_limits->>'catalogBundles')::integer then
    raise exception 'SKILL_CATALOG_LIMIT_EXCEEDED';
  end if;

  for v_entry in select * from jsonb_array_elements(v_entries)
  loop
    if char_length(v_entry->>'description') > (v_limits->>'descriptionChars')::integer then
      raise exception 'SKILL_CATALOG_LIMIT_EXCEEDED';
    end if;
    v_archive_bytes := v_archive_bytes + (v_entry->>'archive_size_bytes')::bigint;
    v_expanded_bytes := v_expanded_bytes + (v_entry->>'expanded_size_bytes')::bigint;
    v_render_bytes := v_render_bytes
      + octet_length(v_entry->>'name')
      + octet_length(v_entry->>'description')
      + octet_length(coalesce(v_entry->>'when_to_use', ''));

    insert into public.analysis_job_skill_snapshot (
      job_id, source_skill_id, source_version_id, source_version,
      name, description, when_to_use,
      archive_bucket, archive_object_key, archive_sha256, archive_size_bytes,
      bundle_hash, bundle_manifest, expanded_size_bytes, file_count, contains_scripts
    ) values (
      p_job_id,
      (v_entry->>'skill_id')::uuid,
      (v_entry->>'version_id')::uuid,
      (v_entry->>'version')::integer,
      v_entry->>'name',
      v_entry->>'description',
      nullif(v_entry->>'when_to_use', ''),
      v_entry->>'archive_bucket',
      v_entry->>'archive_object_key',
      v_entry->>'archive_sha256',
      (v_entry->>'archive_size_bytes')::bigint,
      v_entry->>'bundle_hash',
      v_entry->'bundle_manifest',
      (v_entry->>'expanded_size_bytes')::bigint,
      (v_entry->>'file_count')::integer,
      (v_entry->>'contains_scripts')::boolean
    );
  end loop;

  if v_archive_bytes > (v_limits->>'catalogArchiveBytes')::bigint
     or v_expanded_bytes > (v_limits->>'catalogExpandedBytes')::bigint
     or v_render_bytes > (v_limits->>'catalogRenderBytes')::bigint then
    raise exception 'SKILL_CATALOG_LIMIT_EXCEEDED';
  end if;

  v_hash := public.skill_catalog_hash((
    select coalesce(jsonb_agg(jsonb_build_object(
      'name', entry->>'name',
      'version', entry->>'version',
      'bundleHash', entry->>'bundle_hash',
      'archiveSha256', entry->>'archive_sha256'
    )), '[]'::jsonb)
    from jsonb_array_elements(v_entries) as entry
  ));

  update public.analysis_job
  set skill_catalog_hash = v_hash,
      skill_snapshot_version = 1,
      skill_bundle_count = v_count,
      skill_archive_bytes = v_archive_bytes,
      skill_expanded_bytes = v_expanded_bytes,
      -- 冻结本次生效的目录四项，供 Worker 启动重算使用（与上面的校验用的是同一份 v_limits）。
      skill_catalog_limits = jsonb_build_object(
        'catalogBundles', (v_limits->>'catalogBundles')::integer,
        'catalogRenderBytes', (v_limits->>'catalogRenderBytes')::bigint,
        'catalogArchiveBytes', (v_limits->>'catalogArchiveBytes')::bigint,
        'catalogExpandedBytes', (v_limits->>'catalogExpandedBytes')::bigint
      )
  where id = p_job_id;

  return jsonb_build_object(
    'catalog_hash', v_hash,
    'bundle_count', v_count,
    'archive_bytes', v_archive_bytes,
    'expanded_bytes', v_expanded_bytes
  );
end;
$$;

-- 快照 RPC 增补返回 catalog_limits（历史 Job 该列为 null，直接返回 null）。
create or replace function public.get_story_task_skill_snapshot(
  p_task_id uuid,
  p_worker_id text,
  p_claim_token uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_task public.analysis_story_task;
  v_job public.analysis_job;
begin
  select * into v_task from public.analysis_story_task where id = p_task_id;
  if v_task.id is null
     or v_task.worker_id is distinct from p_worker_id
     or v_task.lease_expires_at is null
     or v_task.lease_expires_at < now()
     or p_claim_token is null
     or v_task.claim_token_digest is distinct from public.agent_claim_token_digest(p_claim_token)
  then
    raise exception 'TASK_LEASE_LOST';
  end if;

  select * into v_job from public.analysis_job where id = v_task.job_id;

  return jsonb_build_object(
    'job_id', v_job.id,
    'snapshot_version', v_job.skill_snapshot_version,
    'catalog_hash', v_job.skill_catalog_hash,
    'archive_bytes', v_job.skill_archive_bytes,
    'expanded_bytes', v_job.skill_expanded_bytes,
    'catalog_limits', v_job.skill_catalog_limits,
    'bundles', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'snapshot_id', snapshot.id,
        'name', snapshot.name,
        'description', snapshot.description,
        'when_to_use', snapshot.when_to_use,
        'version', snapshot.source_version,
        'archive_bucket', snapshot.archive_bucket,
        'archive_object_key', snapshot.archive_object_key,
        'archive_sha256', snapshot.archive_sha256,
        'archive_size_bytes', snapshot.archive_size_bytes,
        'bundle_hash', snapshot.bundle_hash,
        'bundle_manifest', snapshot.bundle_manifest,
        'expanded_size_bytes', snapshot.expanded_size_bytes,
        'file_count', snapshot.file_count,
        'contains_scripts', snapshot.contains_scripts
      ) order by snapshot.name), '[]'::jsonb)
      from public.analysis_job_skill_snapshot snapshot
      where snapshot.job_id = v_job.id
    )
  );
end;
$$;

revoke execute on function public.get_story_task_skill_snapshot(uuid, text, uuid) from public, anon, authenticated;
grant execute on function public.get_story_task_skill_snapshot(uuid, text, uuid) to service_role;

commit;
